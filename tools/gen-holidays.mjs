// 从 chinese-days 生成 holidays.ts。
//
//   npm run gen-holidays
//
// 生成物必须提交：用户是通过 Git 安装扩展的，不会跑这个脚本。
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// 以仓库根为基准，因此从任何工作目录调用都可以。
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PKG_DIR = join(ROOT, "node_modules", "chinese-days");
const SRC = join(PKG_DIR, "dist", "years");
const OUT = join(ROOT, "holidays.ts");

// 覆盖前两年到次年：给跨年查询留出余量，又不会因为写死年份而悄悄过期。
const currentYear = new Date().getUTCFullYear();
const YEARS = [currentYear - 2, currentYear - 1, currentYear, currentYear + 1];

let pkg;
try {
  pkg = JSON.parse(readFileSync(join(PKG_DIR, "package.json"), "utf8"));
} catch {
  console.error(
    "找不到 chinese-days。请先在仓库根执行：npm install",
  );
  process.exit(1);
}

const available = new Set(
  readdirSync(SRC)
    .filter((name) => name.endsWith(".json"))
    .map((name) => Number(name.slice(0, 4))),
);

const holidays = [];
const makeup = [];
const missing = [];

for (const year of YEARS) {
  if (!available.has(year)) {
    missing.push(year);
    continue;
  }
  const raw = JSON.parse(readFileSync(join(SRC, `${year}.json`), "utf8"));
  // 值形如 "English,中文,序号"，取中文名。
  for (const [date, meta] of Object.entries(raw.holidays ?? {})) {
    holidays.push([date, String(meta).split(",")[1] ?? ""]);
  }
  for (const [date, meta] of Object.entries(raw.workdays ?? {})) {
    makeup.push([date, String(meta).split(",")[1] ?? ""]);
  }
}

if (holidays.length === 0) {
  console.error("没有解析出任何节假日数据，未写入文件。");
  process.exit(1);
}

holidays.sort((a, b) => a[0].localeCompare(b[0]));
makeup.sort((a, b) => a[0].localeCompare(b[0]));

const rows = (list) => list.map(([d, n]) => `  "${d}": "${n}",`).join("\n");
const covered = YEARS.filter((year) => available.has(year));

const out = `// AUTO-GENERATED by tools/gen-holidays.mjs — do not edit by hand.
//
// Source: vsme/chinese-days (dist/years/<year>.json), which transcribes
// 国务院办公厅《关于<year>年部分节假日安排的通知》.
// Regenerate after the State Council publishes the next year's arrangement.
//
// Coverage: ${covered.join(", ")}
${missing.length > 0 ? `// NOT YET PUBLISHED when this file was generated: ${missing.join(", ")}\n` : ""}
/** 放假休息日 (法定节假日含调休连休) — 这些日期全天按空闲时段计价。 */
export const HOLIDAYS: Readonly<Record<string, string>> = {
${rows(holidays)}
};

/**
 * 调休上班日 — 被调整为工作日的周末。
 *
 * DeepSeek 的规则原文是「周一至周五…为高峰时段；其余时段，包括周末…均为空闲时段」，
 * 按字面理解调休周末仍算空闲（本扩展默认如此）。若你希望调休上班日按高峰处理，
 * 设置环境变量 OMP_DEEPSEEK_MAKEUP_AS_PEAK=1。
 */
export const MAKEUP_WORKDAYS: Readonly<Record<string, string>> = {
${rows(makeup)}
};

/** 数据覆盖的年份，用于在超出范围时给出提示。 */
export const COVERED_YEARS: readonly number[] = [${covered.join(", ")}];

/** 生成这份数据时所用的上游包版本，用于比对是否存在更新。 */
export const DATA_SOURCE = {
  package: "chinese-days",
  version: "${pkg.version}",
  generatedAt: "${new Date().toISOString()}",
} as const;
`;

writeFileSync(OUT, out);
console.log(`已写入 ${OUT}`);
console.log(`  节假日 ${holidays.length} 条，调休上班日 ${makeup.length} 条`);
console.log(`  覆盖年份：${covered.join(", ")}`);
if (missing.length > 0) {
  console.log(`  尚未公布（已跳过）：${missing.join(", ")}`);
}
console.log(`  上游版本：chinese-days ${pkg.version}`);
